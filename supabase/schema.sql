create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null default 'EcoSathi user',
  role text not null default 'resident' check (role in ('resident', 'worker', 'administrator')),
  created_at timestamptz not null default now()
);

create table if not exists public.locations (
  id bigint generated by default as identity primary key,
  name text not null unique,
  latitude double precision not null,
  longitude double precision not null,
  location_type text not null default 'collection_point',
  created_at timestamptz not null default now()
);

create table if not exists public.bins (
  id bigint generated by default as identity primary key,
  location_id bigint not null references public.locations(id) on delete cascade,
  waste_type text not null default 'mixed',
  capacity integer not null default 100 check (capacity > 0)
);

create table if not exists public.reports (
  id bigint generated by default as identity primary key,
  code text not null unique,
  user_id uuid not null references auth.users(id) on delete cascade,
  location_id bigint references public.locations(id),
  title text not null,
  location text not null,
  category text not null,
  priority text not null check (priority in ('Low', 'Medium', 'High', 'Urgent')),
  status text not null default 'Submitted' check (status in ('Submitted', 'Needs review', 'Verified', 'Assigned', 'In Progress', 'Resolved', 'Rejected')),
  description text,
  source text not null default 'text' check (source in ('text', 'voice', 'webhook')),
  confirmed boolean not null default false,
  idempotency_key text unique,
  resolved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.report_links (
  id bigint generated by default as identity primary key,
  report_id bigint not null references public.reports(id) on delete cascade,
  canonical_report_id bigint not null references public.reports(id) on delete cascade,
  match_reason text not null,
  confidence double precision not null default 0.5 check (confidence between 0 and 1),
  reviewed boolean not null default false,
  created_at timestamptz not null default now(),
  unique (report_id, canonical_report_id)
);

create table if not exists public.workflow_runs (
  id uuid primary key default gen_random_uuid(),
  report_id bigint references public.reports(id) on delete cascade,
  kind text not null check (kind in ('report_processing', 'route_generation')),
  status text not null default 'queued' check (status in ('queued', 'running', 'succeeded', 'failed')),
  error text,
  algorithm_version text,
  started_at timestamptz,
  completed_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.collection_plans (
  id uuid primary key default gen_random_uuid(),
  status text not null default 'proposed' check (status in ('proposed', 'active', 'completed', 'cancelled')),
  algorithm_version text not null default 'nearest-neighbor-v1',
  total_distance double precision not null default 0,
  baseline_distance double precision not null default 0,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

create table if not exists public.collection_stops (
  id bigint generated by default as identity primary key,
  plan_id uuid not null references public.collection_plans(id) on delete cascade,
  report_id bigint not null references public.reports(id) on delete cascade,
  location_id bigint references public.locations(id),
  sequence integer not null,
  worker_status text not null default 'pending' check (worker_status in ('pending', 'in_progress', 'completed', 'skipped')),
  completed_at timestamptz,
  unique (plan_id, sequence)
);

create table if not exists public.audit_events (
  id bigint generated by default as identity primary key,
  actor_id uuid references auth.users(id),
  entity_type text not null,
  entity_id text not null,
  action text not null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

